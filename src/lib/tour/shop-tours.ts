export type ShopTourId = keyof typeof SHOP_TOURS;

export function getShopTour(id: ShopTourId): Tour {
  return SHOP_TOURS[id];
}

/** `/shop/profile` swaps its whole body per tab, so each tab gets its own tour. */
export function profileTourId(tab: "info" | "hours" | "security"): ShopTourId {
  switch (tab) {
    case "hours":
      return "shop-profile-hours";
    case "security":
      return "shop-profile-security";
    default:
      return "shop-profile-info";
  }
}
